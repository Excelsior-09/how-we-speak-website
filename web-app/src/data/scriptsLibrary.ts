// Helper functions for search and category filtering
export function getScriptsByCategory(categoryId: string): ScriptRecord[] {
  if (!categoryId || categoryId === 'ALL') return SCRIPTS_LIBRARY;
  return SCRIPTS_LIBRARY.filter((s) => s.category === categoryId);
}

export function searchScripts(query: string, categoryId: string = 'ALL', tone: string = 'ALL'): ScriptRecord[] {
  const cleanQ = (query || '').toLowerCase().trim();
  return SCRIPTS_LIBRARY.filter((s) => {
    const matchesCategory = categoryId === 'ALL' || s.category === categoryId;
    const matchesTone = tone === 'ALL' || s.tone === tone;
    if (!matchesCategory || !matchesTone) return false;

    if (!cleanQ) return true;
    return (
      s.title.toLowerCase().includes(cleanQ) ||
      s.situation.toLowerCase().includes(cleanQ) ||
      s.goal.toLowerCase().includes(cleanQ) ||
      s.script.toLowerCase().includes(cleanQ) ||
      s.whyItWorks.toLowerCase().includes(cleanQ) ||
      s.tags.some((t) => t.toLowerCase().includes(cleanQ))
    );
  });
}

export type ScriptItem = ScriptRecord;

